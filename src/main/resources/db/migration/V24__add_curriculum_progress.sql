CREATE TABLE curriculum_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_progress_id BIGINT NOT NULL REFERENCES topic_progress(id),
    curriculum_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    UNIQUE (topic_progress_id, curriculum_id)
);

INSERT INTO curriculum_progress (topic_progress_id, curriculum_id, created_at, updated_at)
SELECT lp.topic_progress_id, l.curriculum_id, MIN(lp.created_at), MAX(lp.updated_at)
FROM lesson_progress lp
JOIN lessons l ON l.id = lp.lesson_id
GROUP BY lp.topic_progress_id, l.curriculum_id;

ALTER TABLE lesson_progress ADD COLUMN curriculum_progress_id BIGINT REFERENCES curriculum_progress(id);

UPDATE lesson_progress lp
SET curriculum_progress_id = cp.id
FROM lessons l, curriculum_progress cp
WHERE l.id = lp.lesson_id
  AND cp.curriculum_id = l.curriculum_id
  AND cp.topic_progress_id = lp.topic_progress_id;

ALTER TABLE lesson_progress ALTER COLUMN curriculum_progress_id SET NOT NULL;
ALTER TABLE lesson_progress DROP COLUMN topic_progress_id;
ALTER TABLE lesson_progress ADD CONSTRAINT lesson_progress_curriculum_lesson_unique
    UNIQUE (curriculum_progress_id, lesson_id);
