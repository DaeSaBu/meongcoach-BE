ALTER TABLE topic_progress RENAME TO topic_selection;

CREATE TABLE topic_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    topic_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    UNIQUE (user_id, topic_id)
);

INSERT INTO topic_progress (user_id, topic_id, created_at, updated_at)
SELECT lp.user_id, c.topic_id, MIN(lp.created_at), MAX(lp.updated_at)
FROM lesson_progress lp
JOIN lessons l ON l.id = lp.lesson_id
JOIN curriculums c ON c.id = l.curriculum_id
GROUP BY lp.user_id, c.topic_id;

ALTER TABLE lesson_progress ADD COLUMN topic_progress_id BIGINT REFERENCES topic_progress(id);

UPDATE lesson_progress lp
SET topic_progress_id = tp.id
FROM lessons l, curriculums c, topic_progress tp
WHERE l.id = lp.lesson_id
  AND c.id = l.curriculum_id
  AND tp.topic_id = c.topic_id
  AND tp.user_id = lp.user_id;

ALTER TABLE lesson_progress ALTER COLUMN topic_progress_id SET NOT NULL;
ALTER TABLE lesson_progress DROP COLUMN user_id;
ALTER TABLE lesson_progress ADD CONSTRAINT lesson_progress_topic_lesson_unique UNIQUE (topic_progress_id, lesson_id);
