ALTER TABLE "user_profiles" ADD COLUMN "id" BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE "users" ADD COLUMN "profile_id" BIGINT UNIQUE;

UPDATE "users" u
SET "profile_id" = p."id"
FROM "user_profiles" p
WHERE p."user_id" = u."id";

ALTER TABLE "user_profiles" DROP COLUMN "user_id";
ALTER TABLE "user_profiles" ADD PRIMARY KEY ("id");
ALTER TABLE "users" ADD FOREIGN KEY ("profile_id") REFERENCES "user_profiles" ("id");
